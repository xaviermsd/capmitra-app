/**
 * Effect packs: one-click items grouped by category.
 *
 * A pack is plain data (JSON-friendly): each item names an *action* that the
 * app knows how to perform (add an effect, a transition, a sound, music, a text
 * style, beat-synced effects, or a preset combining several). New packs can be
 * registered in code (registerPack) or imported as a .json file without any
 * code changes, as long as they use these actions. See docs/EFFECT_PACKS.md.
 */
