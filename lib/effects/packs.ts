export type EffectAction =
  /** Add a video effect at the playhead (or over the whole video). */
  | { type: "fx"; fx: FxType; intensity?: number; length?: number; whole?: boolean; sfx?: string }
  /** Set the transition on the selected cut, or every cut. */
  | { type: "transition"; kind: TransitionKind; duration: number; sfx?: string }
  /** Place a sound effect at the playhead. */
  | { type: "sfx"; sfx: string }
  /** Use a generated music track as background music. */
  | { type: "music"; style: string; volume?: number }
  /** Change the caption look (any CaptionStyle fields). */
  | { type: "text"; style: Partial<CaptionStyle> }
  /** Put an effect on music beats. */
  | { type: "beat-sync"; fx: FxType; every: number; intensity?: number; sfx?: string; alternate?: FxType }
  /** Put an effect (and sound) on highlighted keywords. */
  | { type: "keyword-sync"; fx: FxType; intensity?: number; sfx?: string }
  /** Several actions at once (one undo step). */
  | { type: "preset"; steps: EffectAction[] };

export interface EffectItem {
  id: string;
  name: string;
  desc?: string;
  categories: EffectCategory[];
  /** Emoji or short glyph shown on the tile. */
  icon?: string;
  badge?: "hot" | "new";
  action: EffectAction;
}

export interface EffectPack {
  id: string;
  name: string;
  version: string;
  author: string;
  /** Licence of any media referenced by the pack. */
  license: string;
  items: EffectItem[];
}

const packs = new Map<string, EffectPack>();

export function registerPack(p: EffectPack): void {
  packs.set(p.id, p);
}
export function unregisterPack(id: string): void {
  packs.delete(id);
}
export function allPacks(): EffectPack[] {
  return [...packs.values()];
}
export function itemsIn(cat: EffectCategory): (EffectItem & { pack: string })[] {
  const out: (EffectItem & { pack: string })[] = [];
  for (const p of packs.values()) for (const it of p.items) if (it.categories.includes(cat)) out.push({ ...it, pack: p.id });
  return out;
}

const ACTIONS = new Set(["fx", "transition", "sfx", "music", "text", "beat-sync", "keyword-sync", "preset"]);

/** Check an imported pack (data only). Throws a readable error. */
export function validatePack(raw: unknown): EffectPack {
  const p = raw as EffectPack;
  if (!p || typeof p !== "object" || typeof p.id !== "string" || typeof p.name !== "string" || !Array.isArray(p.items)) throw new Error("This isn't a CapMitra effect pack (needs id, name and items).");
  if (p.id === CORE_PACK.id) throw new Error("That pack id is reserved.");
  const check = (a: EffectAction, depth = 0): void => {
    if (!a || typeof a !== "object" || !ACTIONS.has((a as { type: string }).type)) throw new Error(`Unknown action in pack “${p.name}”.`);
    if (a.type === "preset") { if (depth > 2 || !Array.isArray(a.steps)) throw new Error("Presets can't nest that deep."); a.steps.forEach((s) => check(s, depth + 1)); }
  };
  for (const it of p.items) {
    if (typeof it.id !== "string" || typeof it.name !== "string" || !Array.isArray(it.categories)) throw new Error("Every item needs id, name and categories.");
    check(it.action);
  }
  return { ...p, version: p.version ?? "1", author: p.author ?? "unknown", license: p.license ?? "see pack" };
}

